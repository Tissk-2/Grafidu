"use client";

import Link from "next/link";
import { usePathname, useRouter } from "next/navigation";
import { useState } from "react";

const NAV_ITEMS = [
  { href: "/admin/home", label: "Ringkasan", icon: <HomeIcon /> },
  { href: "/admin/users", label: "Akun", icon: <UsersIcon /> },
  { href: "/admin/classes", label: "Kelas", icon: <ClassIcon /> },
  { href: "/admin/announcements", label: "Pengumuman", icon: <MegaphoneIcon /> },
  { href: "/admin/settings", label: "Pengaturan", icon: <GearIcon /> },
];

export default function AdminNav({ name, email }: { name: string; email: string }) {
  const pathname = usePathname();
  const router = useRouter();
  const [busy, setBusy] = useState(false);

  function isActive(href: string): boolean {
    if (href === "/admin/home") return pathname === "/admin" || pathname.startsWith("/admin/home");
    return pathname.startsWith(href);
  }

  async function logout() {
    if (busy) return;
    setBusy(true);
    // Frontend-only: session clearing happens server-side in the real flow.
    router.push("/login");
  }

  const initial = name.trim().charAt(0).toUpperCase() || "A";

  return (
    <>
      <nav className="adm-nav" aria-label="Navigasi admin">
        {NAV_ITEMS.map((item) => (
          <Link
            key={item.href}
            href={item.href}
            className={isActive(item.href) ? "on" : ""}
            aria-label={item.label}
            aria-current={isActive(item.href) ? "page" : undefined}
          >
            {item.icon}
            <span>{item.label}</span>
          </Link>
        ))}
      </nav>
      <div className="adm-side-foot">
        <div className="adm-side-user">
          <span className="avatar" aria-hidden="true">{initial}</span>
          <div>
            <b>{name}</b>
            <span>{email}</span>
          </div>
          <button type="button" className="adm-logout" onClick={logout} disabled={busy} aria-label="Keluar" title="Keluar">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
              <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
              <path d="m16 17 5-5-5-5" />
              <path d="M21 12H9" />
            </svg>
          </button>
        </div>
      </div>
    </>
  );
}

